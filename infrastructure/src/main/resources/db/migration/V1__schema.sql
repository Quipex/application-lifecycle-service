CREATE TABLE applications (
    id             UUID PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    body           VARCHAR(10000) NOT NULL,
    state          VARCHAR(16) NOT NULL,
    publication_id BIGINT UNIQUE,
    version        BIGINT NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_applications_publication_state CHECK (
        (state = 'PUBLISHED' AND publication_id IS NOT NULL)
        OR (state <> 'PUBLISHED' AND publication_id IS NULL)
    )
);

CREATE TABLE audit_record (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(32) NOT NULL,
    aggregate_id   VARCHAR(64) NOT NULL,
    actor          VARCHAR(64) NOT NULL,
    event          VARCHAR(16) NOT NULL,
    state_from     VARCHAR(16),
    state_to       VARCHAR(16) NOT NULL,
    reason         VARCHAR(512),
    occurred_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_aggregate_history
    ON audit_record (aggregate_type, aggregate_id, occurred_at, id);

CREATE SEQUENCE publication_id_seq START WITH 1 INCREMENT BY 1;